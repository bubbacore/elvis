import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary/types";
import { PRIMITIVES_FILE, SEMANTIC_FILE } from "./tokens.ts";

export const CSS_PREFIX = "bubba";

const HEADER = "Generated by @bubbacore/elvis from tokens/semantic.tokens.json. Do not edit.";
const JSON_DESCRIPTION =
  "Tokens semânticos do Bubba, gerados pelo @bubbacore/elvis a partir de tokens/semantic.tokens.json, com as referências já resolvidas. Não edite este arquivo.";

// Only the semantic tokens are public. The primitives are included to resolve the references.
function isSemantic(token: TransformedToken): boolean {
  return token.isSource;
}

// font.width holds a percentage of the wdth axis, which CSS reads in font-stretch.
StyleDictionary.registerTransform({
  name: "bubba/font-width/percent",
  type: "value",
  transitive: true,
  filter: (token) => token.path[0] === "font" && token.path[1] === "width",
  transform: (token) => `${token.$value}%`,
});

// A DTCG tree of the semantic tokens with their references already resolved.
StyleDictionary.registerFormat({
  name: "bubba/json/resolved",
  format: ({ dictionary }) => {
    const tree: Record<string, unknown> = {
      $description: JSON_DESCRIPTION,
    };
    for (const token of dictionary.allTokens) {
      let group = tree;
      for (const key of token.path.slice(0, -1)) {
        group[key] ??= {};
        group = group[key] as Record<string, unknown>;
      }
      group[token.path.at(-1) as string] = {
        $type: token.$type,
        $value: token.$value,
        ...(token.$description ? { $description: token.$description } : {}),
      };
    }
    return `${JSON.stringify(tree, null, 2)}\n`;
  },
});

export type TokenOutput = { path: string; data: Buffer };

// Builds tokens.css and tokens.json in memory from the token sources.
export async function buildTokenOutputs(root: string): Promise<TokenOutput[]> {
  const cssTransforms = StyleDictionary.hooks.transformGroups.css ?? [];
  const dictionary = new StyleDictionary({
    include: [`${root}/${PRIMITIVES_FILE}`],
    source: [`${root}/${SEMANTIC_FILE}`],
    usesDtcg: true,
    log: { warnings: "error", verbosity: "silent" },
    platforms: {
      css: {
        prefix: CSS_PREFIX,
        transforms: [...cssTransforms, "bubba/font-width/percent"],
        files: [
          {
            destination: "tokens.css",
            format: "css/variables",
            filter: isSemantic,
            options: { outputReferences: false, fileHeader: () => [HEADER] },
          },
        ],
      },
      json: {
        // Only the name changes, so the values stay in the DTCG format.
        transforms: ["name/kebab"],
        files: [{ destination: "tokens.json", format: "bubba/json/resolved", filter: isSemantic }],
      },
    },
  });
  const outputs: TokenOutput[] = [];
  for (const platform of ["css", "json"]) {
    for (const file of await dictionary.formatPlatform(platform)) {
      if (typeof file.output !== "string" || !file.destination) {
        throw new Error(`Style Dictionary returned no output for ${platform}`);
      }
      outputs.push({ path: file.destination, data: Buffer.from(file.output) });
    }
  }
  return outputs;
}
